// Demo ölçümleri ve şema göçünün öğrenme kanıtını kirletmediğini sınar.
import assert from 'node:assert/strict';
import { gocler } from '../kaynak/cekirdek/gocler.js';
import { demoSaglayici } from '../kaynak/cekirdek/ai/demo-koc.js';
import { yukle, al, degistir } from '../kaynak/cekirdek/depo.js';
import { sonucuIsle } from '../kaynak/cekirdek/gorusme-sonucu.js';
const bellek = new Map();
globalThis.localStorage = { getItem: k => bellek.get(k) || null, setItem: (k,v) => bellek.set(k,v) };
yukle();
degistir(v => { v.profil.seviye = 'B2'; v.hafiza = [{id:'h1',seri:2,durum:'aktif'}]; });
const oturum = demoSaglayici.oturumAc({tur:'tanisma',profil:al().profil});
oturum.cevapla('I am from Istanbul and I like reading books', 0.99);
const sonuc = oturum.bitir(60);
for (const key of ['akicilik','telaffuz','seviyeTahmini']) assert.equal(sonuc[key],null);
sonuc.hafizaSonuclari = [{id:'h1',basari:true}];
sonucuIsle(sonuc);
assert.equal(al().profil.seviye,'B2');
assert.equal(al().profil.tanismaYapildi,true);
assert.equal(al().hafiza[0].seri,2);
assert.equal(al().gorusmeler.length,1);
assert.equal(Object.values(al().gunluk)[0].dakika,1);
assert.deepEqual(Object.values(al().gunluk)[0].akicilik,[]);
const eski = gocler[2](gocler[1](null));
eski.semaSurumu=2;
eski.hafiza=[{id:'eski',tur:'telaffuz'}];
eski.gunluk={x:{dakika:4,akicilik:[99]}};
eski.sonGorusme={akicilik:99,telaffuz:[{puan:99}],seviyeTahmini:'B1'};
eski.gorusmeler=[eski.sonGorusme];
const once=JSON.stringify(eski);
bellek.set('kk:veri',once);
yukle();
assert.equal(bellek.get('kk:yedek'),once);
assert.equal(al().semaSurumu,3);
assert.deepEqual(al().hafiza,[]);
assert.equal(al().demoArsivi.hafiza[0].id,'eski');
assert.equal(al().demoArsivi.sonGorusme.akicilik,99);
assert.equal(al().sonGorusme.akicilik,null);
assert.deepEqual(al().gunluk.x.akicilik,[]);
assert.equal(al().gunluk.x.dakika,4);
const tekrar=JSON.stringify(al());
yukle();
assert.equal(JSON.stringify(al()),tekrar);
console.log('Demo sonucu, profil/hafıza izolasyonu, süre kaydı, göç, yedek ve yeniden açılış kontrolleri geçti.');
